def fmt_price(price, lang):
    if price is None:
        return LOC[lang]["no_price"]
    return f"{int(round(price)):,} {LOC[lang]['currency']}"


def fmt_spec(value, lang):
    if isinstance(value, bool):
        return ("Yes" if value else "No") if lang == "en" else ("نعم" if value else "لا")
    return str(value)


def summary_text(category, prefs, lang):
    loc = LOC[lang]
    parts = [loc["categories"].get(category, category or "")]
    if prefs.get("budget"):
        parts.append(loc["summary_budget"].format(amount=fmt_price(prefs["budget"], lang)))
    if prefs.get("priority_features"):
        parts.append(loc["summary_priority"].format(items=("، " if lang == "ar" else ", ").join(loc["priorities"].get(p, p) for p in prefs["priority_features"])))
    if prefs.get("preferred_brands"):
        parts.append(loc["summary_brands"].format(items=", ".join(prefs["preferred_brands"])))
    return " · ".join(x for x in parts if x)


def winner_reasons(winner, others, prefs, lang):
    from app.services.scoring_service import canonical_priority, metric_for

    loc = LOC[lang]["reasons"]
    out = []
    for pri in prefs.get("priority_features") or []:
        cp = canonical_priority(pri)
        mine = metric_for(winner, cp)
        if mine is None:
            continue
        rivals = [m for m in (metric_for(o, cp) for o in others) if m is not None]
        label = LOC[lang]["priorities"].get(pri, pri)
        if rivals and mine >= max(rivals):
            out.append(loc["best_priority"].format(p=label))
        elif mine >= 70:
            out.append(loc["strong_priority"].format(p=label))
    priced = [o["price"] for o in others if o.get("price") is not None]
    if winner["price"] is not None and priced and winner["price"] <= min(priced):
        out.append(loc["lowest_price"])
    budget = prefs.get("budget")
    if budget and winner["price"] is not None and winner["price"] < budget:
        out.append(loc["under_budget"].format(amount=fmt_price(budget - winner["price"], lang)))
    if winner["rating"] >= 4.4:
        out.append(loc["high_rating"].format(rating=winner["rating"]))
    brands = [b.lower() for b in prefs.get("preferred_brands") or []]
    if brands and winner["brand"].lower() in brands:
        out.append(loc["brand"])
    return out or [loc["balanced"]]


def render_notes(notes, lang, names=None, category=None):
    names = names or {}
    out = []
    for n in notes:
        code, _, arg = n.partition(":")
        template = LOC[lang]["notes"].get(code)
        if not template:
            continue
        out.append(template.format(name=names.get(int(arg), "") if arg.isdigit() else "", category=LOC[lang]["categories"].get(category, category or "")))
    return list(dict.fromkeys(out))


def card(product, comparison_specs, lang, reasons=None, reviews=None):
    specs = {SPEC_NAMES[lang].get(k, k): fmt_spec(product["specs"][k], lang) for k in comparison_specs if k in product["specs"]}
    return {
        "id": product["id"],
        "name": product["name"],
        "brand": product["brand"],
        "category": product["category"],
        "price": product["price"],
        "price_text": fmt_price(product["price"], lang),
        "price_verified": product["price_verified"],
        "available": product["available"],
        "rating": product["rating"],
        "value_score": product.get("value_score"),
        "score_breakdown": product.get("score_breakdown"),
        "key_specs": specs,
        "image_url": product.get("image_url", ""),
        "reasons": reasons or [],
        "reviews": reviews or [],
    }


def quote(review):
    return f"“{review['text']}” ({review['rating']}/5)"


def markdown_table(cards, lang):
    loc = LOC[lang]
    names = [c["name"] for c in cards]
    rows = [("", names), (("Price" if lang == "en" else "السعر"), [c["price_text"] for c in cards]),
            (loc["value"].capitalize() if lang == "en" else loc["value"], [str(c["value_score"]) if c["value_score"] is not None else "-" for c in cards]),
            (loc["rating"].capitalize() if lang == "en" else loc["rating"], [str(c["rating"]) for c in cards])]
    spec_keys = []
    for c in cards:
        for k in c["key_specs"]:
            if k not in spec_keys:
                spec_keys.append(k)
    for k in spec_keys:
        rows.append((k, [c["key_specs"].get(k, "-") for c in cards]))
    lines = ["| " + " | ".join([rows[0][0] or ("Spec" if lang == "en" else "المواصفة")] + rows[0][1]) + " |",
             "|" + "---|" * (len(cards) + 1)]
    for label, vals in rows[1:]:
        lines.append("| " + " | ".join([label] + vals) + " |")
    return "\n".join(lines)
